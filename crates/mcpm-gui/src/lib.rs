use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicBool, Ordering};

/// Set by "Restart window": start a fresh window once this one has closed.
pub static RELAUNCH: AtomicBool = AtomicBool::new(false);

/// 64x64 RGBA, generated by `tools/gen_icon.py`.
const WINDOW_ICON: &[u8] = include_bytes!("../../../assets/window-icon.rgba");

/// After an update the running exe is `mcpm.exe.old`; what to start next is `mcpm.exe`.
pub fn stable_exe(exe: &Path) -> PathBuf {
    match exe.file_name().and_then(|n| n.to_str()) {
        Some(n) if n.to_lowercase().ends_with(".exe.old") => exe.with_file_name(&n[..n.len() - 4]),
        _ => exe.to_path_buf(),
    }
}

fn window_icon() -> eframe::egui::IconData {
    eframe::egui::IconData {
        rgba: WINDOW_ICON.to_vec(),
        width: 64,
        height: 64,
    }
}

/// Opens the window and blocks until it is closed. Starts the daemon when needed; closing the
/// window leaves the daemon running.
pub fn run(exe: PathBuf) -> anyhow::Result<()> {
    let exe = stable_exe(&exe);
    let home = client::state_dir();
    let options = eframe::NativeOptions {
        viewport: eframe::egui::ViewportBuilder::default()
            .with_title("MCP Manager")
            .with_icon(window_icon())
            .with_inner_size([1100.0, 720.0])
            .with_min_inner_size([820.0, 520.0]),
        renderer: eframe::Renderer::Glow,
        ..Default::default()
    };
    let again = exe.clone();
    eframe::run_native(
        "MCP Manager",
        options,
        Box::new(move |cc| Ok(Box::new(app::App::new(cc, home, exe)))),
    )
    .map_err(|e| anyhow::anyhow!("window failed: {e}"))?;
    if RELAUNCH.load(Ordering::SeqCst) {
        let _ = std::process::Command::new(again).arg("gui").spawn();
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn icon_matches_its_size() {
        assert_eq!(WINDOW_ICON.len(), 64 * 64 * 4);
    }

    #[test]
    fn stable_exe_strips_the_update_suffix() {
        assert_eq!(
            stable_exe(Path::new(r"C:\apps\mcpm.exe.old")),
            PathBuf::from(r"C:\apps\mcpm.exe")
        );
        assert_eq!(
            stable_exe(Path::new(r"C:\apps\mcpm.exe")),
            PathBuf::from(r"C:\apps\mcpm.exe")
        );
    }
}
